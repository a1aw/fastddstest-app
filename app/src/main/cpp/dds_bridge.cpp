enum class EndpointKind
{
    Writer,
    Reader
};

/** Receives onSample(topic, data) on a Fast DDS listener thread. */
class SampleListener : public dds::DataReaderListener
{
public:

    SampleListener(jobject listener_ref, std::string topic)
        : listener_ref_(listener_ref)
        , topic_(std::move(topic))
    {
    }

    ~SampleListener() override = default;

    void on_data_available(dds::DataReader* reader) override;

    /** Stops dispatching; called before the reader is deleted. */
    void stop()
    {
        alive_.store(false, std::memory_order_release);
    }

private:

    std::atomic<bool> alive_{true};
    // Global ref owned by the EndpointHandle, not by this object.
    jobject listener_ref_ = nullptr;
    std::string topic_;
};

struct EndpointHandle
{
    EndpointKind kind = EndpointKind::Writer;
    dds::DomainParticipant* participant = nullptr;
    dds::Publisher* publisher = nullptr;     // writers only
    dds::Subscriber* subscriber = nullptr;   // readers only
    dds::DataWriter* writer = nullptr;       // writers only
    dds::DataReader* reader = nullptr;       // readers only
    dds::Topic* topic = nullptr;             // borrowed from the participant
    SampleListener* listener = nullptr;      // readers only, may be null
    jobject listener_ref = nullptr;          // global ref, may be null
};

struct ParticipantHandle
{
    dds::DomainParticipant* participant = nullptr;

    // Set by nativeCreateWriter/nativeCreateReader so nativeDiscoveredPeers can
    // report endpoint-level matches (the only reliable signal in server mode).
    dds::DataWriter* writer = nullptr;
    dds::DataReader* reader = nullptr;
};

