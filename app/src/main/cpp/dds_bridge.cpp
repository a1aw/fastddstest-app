// =============================================================================
// dds_bridge.cpp
//
// JNI bridge between the Android app and Fast DDS 3.6.2 - the middleware release
// that ships with ROS 2 "Lyrical Luth" - over UDPv4.
//
// Java owns the lifecycle and drives it from one single-threaded executor:
//
//     nativeCreateParticipant() -> nativeCreateWriter() -> nativeCreateReader()
//     ... nativeWriteString() / nativeDiscoveredPeers() ...
//     nativeDelete(writer) -> nativeDelete(reader) -> nativeDestroyParticipant()
//
// This translation unit is the only place in the app that knows about Fast DDS.
// The Java layer only ever sees opaque `long` handles; the generated IDL headers
// (String.hpp / StringPubSubTypes.hpp) never leak into Java.
//
// Design notes
// ------------
// * Handles are raw pointers to heap structs, so Java can never dereference them.
//   `ParticipantHandle` and `EndpointHandle` are distinct types and the endpoint
//   carries a `kind` tag so nativeDelete() knows whether to destroy a writer or a
//   reader. Every entry point rejects handle == 0 and returns 0 on any failure;
//   a partially constructed object is always unwound before returning.
// * The participant owns its Topic. Endpoints only borrow the Topic* and
//   nativeDelete() deliberately leaves it alone: the participant's
//   delete_contained_entities() destroys the topic. That is exactly why the
//   teardown order (endpoints first, then the participant) matters - getting it
//   the other way around crashes on a discovery-mode switch.
// * create_topic() refuses a second topic with the same name on the same
//   participant, so the reader reuses the topic the writer already created
//   (lookup_topicdescription()).
// * Listener callbacks arrive on Fast DDS threads. The JavaVM is cached in
//   JNI_OnLoad, every callback attaches with AttachCurrentThreadAsDaemon (never
//   the plain Attach, which would pin the thread), and the StringListener class
//   plus its onSample(String, String) method id are resolved once and held as a
//   global ref. Every local ref is deleted after the call and the callback never
//   blocks: it drains the reader with take_next_sample() and returns.
// * QoS mirrors the rmw_fastrtps defaults - RELIABLE + VOLATILE + KEEP_LAST(10) -
//   on the topic, the writer and the reader. Anything else and a ROS 2 peer
//   silently refuses to match.
// =============================================================================

