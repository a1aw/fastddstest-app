std::string jstring_to_string(JNIEnv* env, jstring value)
{
    if (env == nullptr || value == nullptr)
    {
        return {};
    }
    const char* chars = env->GetStringUTFChars(value, nullptr);
    if (chars == nullptr)
    {
        env->ExceptionClear();
        return {};
    }
    std::string result(chars);
    env->ReleaseStringUTFChars(value, chars);
    return result;
}

/** Java-supplied type name, falling back to the generated String type name. */
std::string resolve_type_name(JNIEnv* env, jstring type_name)
{
    std::string name = jstring_to_string(env, type_name);
    if (name.empty())
    {
        name = kDefaultTypeName;
    }
    return name;
}

/**
 * Applies the rmw_fastrtps defaults to a TopicQos / DataWriterQos / DataReaderQos.
 * All three expose reliability(), durability() and history() with the same shape.
 */
template <typename QosT>
void apply_rmw_qos(QosT& qos)
{
    qos.reliability().kind = dds::RELIABLE_RELIABILITY_QOS;
    qos.durability().kind = dds::VOLATILE_DURABILITY_QOS;
    qos.history().kind = dds::KEEP_LAST_HISTORY_QOS;
    qos.history().depth = kHistoryDepth;
}

/**
 * Registers the generated String type under the given name.
 *
 * RETCODE_PRECONDITION_NOT_MET means "another TypeSupport with that name is
 * already registered", which is the normal case for the reader that follows the
 * writer on the same participant: the registration is there, so we accept it.
 */
bool ensure_type_registered(dds::DomainParticipant* participant, const std::string& type_name)
{
    if (participant == nullptr || type_name.empty())
    {
        return false;
    }

    dds::TypeSupport support(new (std::nothrow) std_msgs::msg::StringPubSubType());
    if (support.empty())
    {
        LOG_E("cannot allocate StringPubSubType");
        return false;
    }

    dds::ReturnCode_t rc = participant->register_type(support, type_name);
    if (rc == dds::RETCODE_OK || rc == dds::RETCODE_PRECONDITION_NOT_MET)
    {
        return true;
    }

    LOG_E("register_type('%s') failed with %d", type_name.c_str(), static_cast<int>(rc));
    return false;
}

/**
 * Returns the participant-owned topic, creating it on first use.
 *
 * create_topic() rejects a duplicate name, so the second endpoint (the reader)
 * has to find the topic the writer already created instead of making a new one.
 */
dds::Topic* find_or_create_topic(
        dds::DomainParticipant* participant,
        const std::string& topic_name,
        const std::string& type_name)
{
    if (participant == nullptr || topic_name.empty() || type_name.empty())
    {
        return nullptr;
    }

    dds::TopicDescription* existing = participant->lookup_topicdescription(topic_name);
    if (existing != nullptr)
    {
        if (existing->get_type_name() != type_name)
        {
            LOG_E("topic '%s' already exists with a different type name", topic_name.c_str());
            return nullptr;
        }
        // lookup_topicdescription() only ever returns Topics we created ourselves.
        return dynamic_cast<dds::Topic*>(existing);
    }

    dds::TopicQos topic_qos;
    if (participant->get_default_topic_qos(topic_qos) != dds::RETCODE_OK)
    {
        LOG_E("get_default_topic_qos failed");
        return nullptr;
    }
    apply_rmw_qos(topic_qos);

    dds::ReturnCode_t ret = dds::RETCODE_OK;
    dds::Topic* topic = participant->create_topic(topic_name, type_name, topic_qos, ret);
    if (topic == nullptr || ret != dds::RETCODE_OK)
    {
        LOG_E("create_topic('%s') failed with %d", topic_name.c_str(), static_cast<int>(ret));
        return nullptr;
    }

    return topic;
}

