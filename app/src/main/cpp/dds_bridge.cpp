void SampleListener::on_data_available(dds::DataReader* reader)
{
    if (reader == nullptr)
    {
        return;
    }
    if (!alive_.load(std::memory_order_acquire))
    {
        return;
    }
    // A null listener is legal: the reader exists so it matches on the remote
    // side, we simply drop whatever arrives.
    if (listener_ref_ == nullptr || g_on_sample_method == nullptr)
    {
        return;
    }

    JNIEnv* env = attach_current_thread();
    if (env == nullptr)
    {
        return;
    }

    std_msgs::msg::String sample;
    dds::SampleInfo info;

    while (alive_.load(std::memory_order_acquire) &&
            reader->take_next_sample(&sample, &info) == dds::RETCODE_OK)
    {
        if (!info.valid_data)
        {
            continue;
        }

        jstring topic = env->NewStringUTF(topic_.c_str());
        jstring data = env->NewStringUTF(sample.data().c_str());
        if (topic != nullptr && data != nullptr)
        {
            env->CallVoidMethod(listener_ref_, g_on_sample_method, topic, data);
        }
        if (topic != nullptr)
        {
            env->DeleteLocalRef(topic);
        }
        if (data != nullptr)
        {
            env->DeleteLocalRef(data);
        }

        if (env->ExceptionCheck())
        {
            // A throwing listener must not kill the DDS thread.
            LOG_W("StringListener.onSample threw; dropping the rest of this batch");
            env->ExceptionClear();
            break;
        }
    }
}

