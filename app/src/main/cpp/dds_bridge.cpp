// Mirrors DdsBridge.MODE_SIMPLE / DdsBridge.MODE_DISCOVERY_SERVER.
constexpr jint kModeSimple = 0;
constexpr jint kModeDiscoveryServer = 1;

// Type name Fast DDS-Gen emits for std_msgs/msg/String (see the set_name() call in
// the generated StringPubSubTypes.cxx). Only used when Java passes an empty name.
constexpr const char* kDefaultTypeName = "std_msgs::msg::dds_::String_";

// rmw_fastrtps defaults. A mismatch here means a ROS 2 peer silently drops us.
constexpr int32_t kHistoryDepth = 10;

constexpr const char* kLogTag = "DdsBridge";

#define LOG_E(...) __android_log_print(ANDROID_LOG_ERROR, kLogTag, __VA_ARGS__)
#define LOG_W(...) __android_log_print(ANDROID_LOG_WARN, kLogTag, __VA_ARGS__)

// -----------------------------------------------------------------------------
// JVM / listener plumbing
//
// The StringListener class and its method id are resolved once and kept alive by
// a global ref, so a callback never has to pay for FindClass/GetMethodID.
// -----------------------------------------------------------------------------

JavaVM* g_vm = nullptr;
jclass g_listener_class = nullptr;
jmethodID g_on_sample_method = nullptr;
std::mutex g_listener_mutex;

JNIEnv* attach_current_thread()
{
    if (g_vm == nullptr)
    {
        return nullptr;
    }
    JNIEnv* env = nullptr;
    // AsDaemon, not AttachCurrentThread: the VM must not keep the Fast DDS thread
    // alive, and a daemon attachment is detached automatically on thread exit.
    if (g_vm->AttachCurrentThreadAsDaemon(&env, nullptr) != JNI_OK)
    {
        return nullptr;
    }
    return env;
}

/**
 * Resolves and caches DdsBridge$StringListener#onSample(String, String).
 *
 * A failure is not fatal: readers are still created, they just drop samples. The
 * lookup is retried lazily from nativeCreateReader(), so a transient failure in
 * JNI_OnLoad() heals itself.
 */
bool ensure_listener_cache(JNIEnv* env)
{
    if (env == nullptr)
    {
        return false;
    }

    std::lock_guard<std::mutex> lock(g_listener_mutex);
    if (g_listener_class != nullptr && g_on_sample_method != nullptr)
    {
        return true;
    }

    jclass local = env->FindClass("com/example/fastddstest/DdsBridge$StringListener");
    if (local == nullptr)
    {
        LOG_E("StringListener class not found");
        env->ExceptionClear();
        return false;
    }

    jmethodID method = env->GetMethodID(local, "onSample",
                    "(Ljava/lang/String;Ljava/lang/String;)V");
    if (method == nullptr)
    {
        LOG_E("StringListener.onSample(String, String) not found");
        env->ExceptionClear();
        env->DeleteLocalRef(local);
        return false;
    }

    g_listener_class = reinterpret_cast<jclass>(env->NewGlobalRef(local));
    g_on_sample_method = method;
    env->DeleteLocalRef(local);

    return g_listener_class != nullptr;
}

